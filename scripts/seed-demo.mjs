function phone() {
  for (;;) {
    const p = `${pick(["2", "5", "9", "4"])}${String(int(0, 9999999)).padStart(7, "0")}`;
    if (!usedPhones.has(p) && p !== "25875529") {
      usedPhones.add(p);
      return p;
    }
  }
}

