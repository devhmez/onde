const updTagDestination = sqlite.prepare(`update tags set destination_type = ?, destination_url = ?, updated_at = ? where id = ?`);
const insView = sqlite.prepare(`insert into page_views (ts, path, locale, device, referrer, visitor) values (?, ?, ?, ?, ?, ?)`);
const codeExists = sqlite.prepare(`select 1 from tags where code = ?`);
const maxOrder = sqlite.prepare(`select max(cast(substr(number, 5) as integer)) as n from orders where number like 'OND-%'`);

function newCode() {
  for (;;) {
    let c = "";
    for (let i = 0; i < 6; i++) c += CODE_ALPHABET[Math.floor(rand() * CODE_ALPHABET.length)];
    if (!codeExists.get(c)) return c;
  }
}
function googleReview() {
  return `https://g.page/r/C${hex(9).toUpperCase().slice(0, 14)}EAE/review`;
}
function destinationFor(kind, customer) {
  const handle = slugify(customer.businessName ?? customer.name);
  if (kind === "stand" || kind === "sticker") {
    return weighted([
      [["google_review", googleReview()], 78],
      [["menu", `https://menu.${handle || "demo"}.tn`], 10],
      [["instagram", `https://www.instagram.com/${handle}`], 12],
    ]);
  }
  return weighted([
    [["instagram", `https://www.instagram.com/${handle}`], 34],
    [["whatsapp", `https://wa.me/216${customer.phone}`], 20],
    [["google_review", googleReview()], 18],
    [["tiktok", `https://www.tiktok.com/@${handle}`], 12],
    [["website", `https://${handle || "demo"}.tn`], 16],
  ]);
}
const KIND_LABEL = { stand: "Review stand", card: "NFC card", keychain: "Keychain", sticker: "Sticker" };
const PACKS = { "pack-cafe": [["stand", 2], ["sticker", 4]], "pack-team": [["card", 5]] };

const summary = sqlite.transaction(() => {
  // ---- customers
  const customers = [];
  const businesses = [...BUSINESSES];
  for (let i = 0; i < 25; i++) {
    const first = pick(FIRST);
    const last = pick(LAST);
    const placeIdx = weighted(PLACES.map((p, j) => [j, PLACE_WEIGHTS[j]]));
    const [gov, cities] = PLACES[placeIdx];
    const isBusiness = businesses.length > 0 && chance(0.64);
    const businessName = isBusiness ? businesses.splice(Math.floor(rand() * businesses.length), 1)[0] : null;
    const createdAt = now - int(2, 62) * DAY - int(0, 20) * 3_600_000;
    const c = {
      name: `${first} ${last}`,
      phone: phone(),
      email: chance(0.45) ? `${slugify(first)}.${slugify(last)}@example.com` : null,
      businessName,
      governorate: gov,
      city: pick(cities),
      address: `${int(1, 120)} ${pick(STREETS)}`,
      createdAt,
    };
    c.id = insCustomer.run(c.name, c.phone, c.email, c.businessName, c.governorate, c.city, c.address, DEMO_NOTE, c.createdAt).lastInsertRowid;
    c.discount = false;
    c.discountUsed = false;
    customers.push(c);
  }

  // ---- orders (chronological so the returning-customer discount follows the real rules)
  const plans = [];
  for (const c of customers) plans.push({ c, at: c.createdAt + int(0, 6) * 3_600_000 });
  while (plans.length < 41) {
    const c = pick(customers);
    plans.push({ c, at: Math.min(now - 3_600_000, c.createdAt + int(1, 40) * DAY + int(0, 12) * 3_600_000) });
  }
  plans.sort((a, b) => a.at - b.at);

  let nextNumber = Math.max(1000, Number(maxOrder.get()?.n ?? 0)) + 1;
  const orders = [];
  for (const { c, at } of plans) {
    const ageDays = (now - at) / DAY;
    const status =
      ageDays > 12 ? weighted([["delivered", 86], ["cancelled", 9], ["shipped", 5]])
      : ageDays > 5 ? weighted([["delivered", 55], ["shipped", 25], ["preparing", 10], ["cancelled", 10]])
      : ageDays > 2 ? weighted([["shipped", 35], ["preparing", 35], ["confirmed", 25], ["cancelled", 5]])
      : weighted([["new", 55], ["confirmed", 30], ["preparing", 15]]);
    const lines = [];
    const nLines = weighted([[1, 70], [2, 25], [3, 5]]);
    const pool = c.businessName
      ? [["stand-white", 32], ["stand-black", 20], ["sticker", 14], ["pack-cafe", 10], ["pack-team", 4], ["card", 12]]
      : [["card", 40], ["keychain", 30], ["sticker", 15], ["stand-white", 10], ["pack-team", 5]];
    const seen = new Set();
    for (let k = 0; k < nLines; k++) {
      const slug = weighted(pool.filter(([s]) => !seen.has(s)));
      seen.add(slug);
      const p = bySlug[slug];
      const qty = p.kind === "pack" ? 1 : weighted([[1, 70], [2, 22], [3, 6], [4, 2]]);
      lines.push({ p, qty });
    }
    const subtotal = lines.reduce((s, l) => s + l.p.price * l.qty, 0);
    const applyDiscount = c.discount && !c.discountUsed;
    const discount = applyDiscount ? Math.round((subtotal * RULES.returningDiscountPct) / 100) : 0;
    const deliveryFee = subtotal >= RULES.freeDeliveryThreshold ? 0 : RULES.deliveryFee;
    const total = subtotal - discount + deliveryFee;
    const locale = chance(0.76) ? "fr" : "en";
    const channel = weighted([["web", 68], ["whatsapp", 27], ["manual", 5]]);
    const number = `OND-${nextNumber++}`;
    const updatedAt = Math.min(now, at + int(1, 4) * DAY);
    const orderId = insOrder.run(
      number, c.id, status, channel, locale, c.name, c.phone, c.email, c.governorate, c.city, c.address,
      chance(0.2) ? pick(["Livrer après 14h svp", "Présentoirs noirs si possible", "Appeler avant la livraison", "Please call before delivery"]) : null,
      subtotal, discount, applyDiscount ? "returning_10" : null, deliveryFee, total, at, updatedAt,
    ).lastInsertRowid;
    if (applyDiscount) {
      if (status === "cancelled") c.discount = true; // restored
      else {
        c.discount = false;
        c.discountUsed = true;
      }
    }
    if (status === "delivered" && !c.discountUsed) c.discount = true;
    const items = lines.map(({ p, qty }) => {
      const destination = c.businessName ? googleReview() : null;
      insItem.run(orderId, p.id, locale === "fr" ? p.name_fr : p.name_en, p.kind, p.price, qty, p.price * qty, c.businessName, destination);
      return { p, qty, destination };
    });
    orders.push({ id: orderId, number, c, status, at, items });
  }
  for (const c of customers) setDiscount.run(c.discount ? 1 : 0, c.id);

  // ---- tags: one per physical unit of fulfilled orders (+ a few made by hand in the admin)
  const tagRows = [];
  function addTag(kind, c, orderId, createdAt, n, variant) {
    const [type, url] = destinationFor(kind, c);
    const code = newCode();
    const owner = c.businessName ?? c.name;
    const label = `${owner} — ${variant ?? KIND_LABEL[kind]} #${n}`;
    const status = chance(0.05) ? "disabled" : "active";
    const id = insTag.run(code, label, kind, c.id, orderId, type, url, status, DEMO_TAG_NOTE, createdAt, createdAt).lastInsertRowid;
    insHistory.run(id, null, null, type, url, createdAt);
    let currentType = type;
    let currentUrl = url;
    if (chance(0.15)) {
      const changedAt = createdAt + int(3, 20) * DAY;
      if (changedAt < now) {
        const [t2, u2] = kind === "stand" ? ["menu", `https://menu.${slugify(owner) || "demo"}.tn`] : ["instagram", `https://www.instagram.com/${slugify(owner)}`];
        insHistory.run(id, type, url, t2, u2, changedAt);
        updTagDestination.run(t2, u2, changedAt, id);
        currentType = t2;
        currentUrl = u2;
      }
    }
    tagRows.push({ id, kind, createdAt, status, type: currentType, url: currentUrl });
  }
  for (const o of orders) {
    if (!["delivered", "shipped", "preparing"].includes(o.status)) continue;
    const createdAt = o.at + int(6, 30) * 3_600_000;
    const counters = {};
    for (const { p, qty } of o.items) {
      const parts = PACKS[p.slug] ?? [[p.kind, 1]];
      for (let q = 0; q < qty; q++) {
        for (const [kind, count] of parts) {
          for (let k = 0; k < count; k++) {
            counters[kind] = (counters[kind] ?? 0) + 1;
            const variant = p.slug === "stand-white" ? "Review stand (white)" : p.slug === "stand-black" ? "Review stand (black)" : undefined;
            addTag(kind, o.c, o.id, Math.min(createdAt, now - 3_600_000), counters[kind], variant);
          }
        }
      }
    }
  }
  while (tagRows.length < 80) {
    const c = pick(customers);
    const kind = weighted([["sticker", 40], ["card", 30], ["keychain", 20], ["stand", 10]]);
    addTag(kind, c, null, Math.max(c.createdAt, now - int(5, 55) * DAY), int(1, 3));
  }

  // ---- taps: per-tag Poisson rate × weekday × growth, hourly curve, NFC/QR + device mix
  const HOURS = [0.2, 0.1, 0.05, 0.05, 0.05, 0.1, 0.3, 0.8, 1.5, 2, 2.2, 2.8, 4, 4.2, 3, 2.4, 2.4, 2.8, 3.5, 4.5, 5, 4.2, 2.5, 1];
  const WEEKDAY = [1.25, 0.85, 0.9, 0.95, 1.0, 1.2, 1.35]; // Sun..Sat
  const KIND_RATE = { stand: 2.6, sticker: 0.9, card: 0.55, keychain: 0.4 };
  const rates = new Map(tagRows.map((t) => [t.id, KIND_RATE[t.kind] * Math.exp((rand() - 0.5) * 1.6)]));
  const start = now - 60 * DAY;
  let expected = 0;
  for (const t of tagRows) {
    const from = Math.max(start, t.createdAt + DAY);
    expected += Math.max(0, (now - from) / DAY) * rates.get(t.id) * 1.05;
  }
  const scale = expected > 0 ? 3000 / expected : 1;
  let tapTotal = 0;
  for (const t of tagRows) {
    if (t.status === "disabled") continue;
    const from = Math.max(start, t.createdAt + DAY);
    let count = 0;
    let last = null;
    for (let day = Math.floor(from / DAY) * DAY; day < now; day += DAY) {
      const dow = new Date(day + TZ).getUTCDay();
      const n = poisson(rates.get(t.id) * scale * WEEKDAY[dow]);
      for (let k = 0; k < n; k++) {
        const hour = weighted(HOURS.map((w, h) => [h, w]));
        const ts = day + hour * 3_600_000 + int(0, 3_599_999) - TZ;
        if (ts < from || ts > now) continue;
        const source = chance(0.18) ? "qr" : "nfc";
        const device = source === "nfc"
          ? weighted([["android", 64], ["ios", 34], ["other", 2]])
          : weighted([["android", 55], ["ios", 33], ["desktop", 8], ["other", 4]]);
        const referer = source === "qr" && chance(0.1) ? "https://www.instagram.com" : null;
        insTap.run(t.id, ts, source, device, referer, `demo${hex(12)}`);
        count++;
        if (!last || ts > last) last = ts;
      }
    }
    tapTotal += count;
    updTagTaps.run(count, last, t.id);
  }

  // ---- page views (cookie-less analytics), growing traffic with weekly pattern
  const PATHS = [
    ["/fr", 30], ["/fr/shop", 18], ["/fr/shop/stand-white", 7], ["/fr/shop/stand-black", 5], ["/fr/shop/card", 5],
    ["/fr/shop/pack-cafe", 4], ["/fr/about", 6], ["/fr/checkout", 4], ["/fr/contact", 3], ["/en", 7], ["/en/shop", 5],
    ["/en/shop/card", 2], ["/en/about", 2], ["/fr/inactive", 1], ["/en/checkout", 1],
  ];
  const REFS = [[null, 55], ["https://www.instagram.com", 18], ["https://www.google.com", 12], ["https://www.facebook.com", 10], ["https://www.tiktok.com", 5]];
  let views = 0;
  for (let d = 59; d >= 0; d--) {
    const day = Math.floor((now - d * DAY) / DAY) * DAY;
    const dow = new Date(day + TZ).getUTCDay();
    const visitors = Math.round((18 + (59 - d) * 0.9) * WEEKDAY[dow] * (0.8 + rand() * 0.4));
    for (let v = 0; v < visitors; v++) {
      const visitor = `demo-${hex(10)}`;
      const device = weighted([["android", 55], ["ios", 30], ["desktop", 13], ["other", 2]]);
      const ref = weighted(REFS);
      const pages = weighted([[1, 50], [2, 25], [3, 15], [4, 10]]);
      const t0 = day + weighted(HOURS.map((w, h) => [h, w])) * 3_600_000 + int(0, 3_000_000) - TZ;
      for (let k = 0; k < pages; k++) {
        const ts = t0 + k * int(20_000, 180_000);
        if (ts > now) break;
        const p = weighted(PATHS);
        insView.run(ts, p, p.startsWith("/en") ? "en" : "fr", device, k === 0 ? ref : null, visitor);
        views++;
      }
    }
  }

  return { customers: customers.length, orders: orders.length, tags: tagRows.length, taps: tapTotal, views };
})();

sqlite.prepare(`insert into audit_log (ts, action, details) values (?, 'demo.seed', ?)`).run(Date.now(), JSON.stringify(summary));
console.log(
  `DEMO data ready in ${dbFile}\n` +
    `  ${summary.customers} customers · ${summary.orders} orders · ${summary.tags} smart links · ${summary.taps} taps · ${summary.views} page views\n` +
    "  Remove it with: node scripts/seed-demo.mjs --clean",
);
sqlite.close();
