#!/usr/bin/env node
// DEMO DATA — opt-in, for local dashboard testing only. Never run it against the production database.
//
//   node scripts/seed-demo.mjs            # (re)generate demo data in $DATABASE_PATH (default ./data/onde.db)
//   node scripts/seed-demo.mjs --clean    # remove all demo data and exit
//   node scripts/seed-demo.mjs --force    # required when NODE_ENV=production
//
// Generates ~25 customers (fictional Tunisian names/cities), ~40 orders over the last 60 days across all statuses,
// ~80 smart links with destinations, ~3000 taps (realistic daily/hourly curve, NFC/QR + device mix) and ~60 days of
// page views. Every demo row is marked so --clean can remove it precisely:
//   customers.notes starts with "[DEMO]", tags.notes = "[DEMO]", page_views.visitor starts with "demo-".
// Orders/items/taps/history of demo customers & tags are removed with them. Real data is never touched.
// The catalog must exist (start the app once — src/instrumentation.ts seeds it — then run this script).
