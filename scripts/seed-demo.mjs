function clean() {
  const demoCustomers = `select id from customers where notes like '[DEMO]%'`;
  const demoOrders = `select id from orders where customer_id in (${demoCustomers})`;
  const r = sqlite.transaction(() => {
    const tags = sqlite
      .prepare(`delete from tags where notes = ? or customer_id in (${demoCustomers}) or order_id in (${demoOrders})`)
      .run(DEMO_TAG_NOTE).changes;
    const orders = sqlite.prepare(`delete from orders where id in (${demoOrders})`).run().changes; // items cascade
    const customers = sqlite.prepare(`delete from customers where notes like '[DEMO]%'`).run().changes;
    const views = sqlite.prepare(`delete from page_views where visitor like 'demo-%'`).run().changes;
    return { customers, orders, tags, views };
  })();
  return r;
}

